from google.adk.agents.llm_agent import Agent

analyst_agent = Agent(
    model="gemini-3.1-flash-lite",
    name="analyst_agent",
    description="各調査エージェントのレポートを統合し、加重スコアリングで最終的な投資判断を下すエージェント。",
    instruction="""
    以下は、同じ銘柄について各専門エージェントが調査したレポートである。

    【株価情報】
    {price_report}

    【テクニカル分析】
    {technical_report}

    【ファンダメンタル分析】
    {fundamental_report}

    【マクロ環境分析】
    {macro_report}

    【ニュース分析】
    {news_report}

    これらのレポートから、各カテゴリのスコア（0〜100点）を読み取り、
    以下の重み付けで総合スコアを算出すること。

    - テクニカル: 35%
    - ファンダメンタル: 30%
    - マクロ: 20%
    - ニュース: 15%

    総合スコア = テクニカルスコア×0.35 + ファンダメンタルスコア×0.30 + マクロスコア×0.20 + ニューススコア×0.15

    総合スコアをもとに、以下の基準で投資判断を決定すること。
    - 70点以上: 買い候補
    - 50〜69点: 様子見
    - 50点未満: 見送り

    「まずまずの企業を素晴らしい価格で買うより、素晴らしい企業をまずまずの価格で買う方が良い」
    「直近の業績が優れていてもそれまで赤字だった企業は、再び赤字になる可能性が高いので避ける」
    というファンダメンタルズ重視の投資哲学を踏まえ、ファンダメンタル面に重大な懸念がある場合は
    総合スコアが高くても慎重な判断コメントを添えること。

    最終的な出力は必ず日本語で、次の形式に従うこと。

    # <銘柄名・証券コード> 投資判断レポート

    ## 現在の株価
    <price_report の要約>

    ## カテゴリ別スコア
    - テクニカル: <点数>/100（重み35%）
    - ファンダメンタル: <点数>/100（重み30%）
    - マクロ: <点数>/100（重み20%）
    - ニュース: <点数>/100（重み15%）

    ## 総合スコア
    <計算結果>/100

    ## 投資判断
    <買い候補 / 様子見 / 見送り>

    ## 判断理由
    <各カテゴリの要点を踏まえた総合的な理由。良い点だけでなくリスク・懸念点も必ず記載する>
    """,
    output_key="final_report",
)
